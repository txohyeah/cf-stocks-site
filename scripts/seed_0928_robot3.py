MOD_ID = 9810
BLK_ID = 9746

for s in STOCKS:
    # stocks（防重：robot 线三只均为站外新股）
    tags = json.dumps(s['tags'], ensure_ascii=False)
    desc = s['desc'].replace("'", "''")
    run(
        "INSERT INTO stocks (code, name, sector, category, subtype, tags, desc, pe_current, pe_date, ttm_buy_range, buy_range_type, tracked, added_at) VALUES ("
        f"'{s['code']}', '{s['name']}', '{s['sector']}', 'frontier', '', "
        f"'{tags}', '{desc}', {s['pe']}, '{PE_DATE}', '{s['buy_range']}', 'price', 1, '{ADDED}')",
        f"stocks {s['code']}"
    )
    # industry_lines（robot 线，lineCat=frontier 对照北特/福莱惯例）
    ln = s['line']
    run(
        "INSERT INTO industry_lines (stock_code, line_id, position, weight, segment, note, sort_order, lineCat) VALUES ("
        f"'{s['code']}', 'robot', '{ln['position']}', '{ln['weight']}', '{ln['segment'].replace(chr(39), chr(39)*2)}', '{ln['note'].replace(chr(39), chr(39)*2)}', 0, 'frontier')",
        f"industry_lines {s['code']}"
    )
    # tracking_rules
    for i, (dim, ind, g, y, r) in enumerate(s['rules']):
        run(
            "INSERT INTO tracking_rules (stock_code, dimension, indicator, red, yellow, green, sort_order) VALUES ("
            f"'{s['code']}', '{dim}', '{ind}', '{r.replace(chr(39), chr(39)*2)}', '{y.replace(chr(39), chr(39)*2)}', '{g.replace(chr(39), chr(39)*2)}', {i})",
            f"rule {s['code']} #{i}"
        )
    # stock_modules + module_blocks（显式 id）
    for mi, (key, mtitle, blocks) in enumerate(s['modules'], 1):
        mid = MOD_ID
        MOD_ID += 1
        run(
            f"INSERT INTO stock_modules (id, stock_code, module_key, title, template_key, sort_order, visible) VALUES "
            f"({mid}, '{s['code']}', '{key}', '{mtitle}', '{key}', {mi}, 1)",
            f"module {mid} {s['code']} {key}"
        )
        for j, (btype, data) in enumerate(blocks, 1):
            run(
                f"INSERT INTO module_blocks (id, module_id, block_type, data_json, sort_order) VALUES "
                f"({BLK_ID}, {mid}, '{btype}', '{data.replace(chr(39), chr(39)*2)}', {j})",
                f"block {BLK_ID} -> module {mid} #{j}"
            )
            BLK_ID += 1

print(f'\n== seed 完成：modules 到 {MOD_ID-1}，blocks 到 {BLK_ID-1} ==')
